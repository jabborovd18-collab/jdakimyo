/**
 * Javobni tekshiruvchi yordamchi funksiya
 */
export function javobniTekshir(savol, berilganJavob) {
  if (!savol || berilganJavob === undefined || berilganJavob === null) return false;

  if (savol.turi === 'ochiq') {
    const tozaBerilgan = String(berilganJavob).trim().replace(',', '.');
    const tozaKutilgan = String(savol.correct).trim().replace(',', '.');
    const bSon = parseFloat(tozaBerilgan);
    const kSon = parseFloat(tozaKutilgan);

    if (!isNaN(bSon) && !isNaN(kSon)) {
      return Math.abs(bSon - kSon) < 0.05;
    }
    return tozaBerilgan === tozaKutilgan;
  }

  // Variantli savollar
  return String(berilganJavob).trim().toUpperCase() === String(savol.correct).trim().toUpperCase();
}
